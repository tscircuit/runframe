import { expect, test } from "bun:test"
import { Circuit } from "@tscircuit/core"
import * as React from "react"
import { adaptCachedDatasheet } from "lib/optional-features/importing/datasheet-catalog/adapter"
import type { CachedDatasheet } from "lib/optional-features/importing/datasheet-catalog/types"

const fixture = (
  overrides: Partial<CachedDatasheet> = {},
): CachedDatasheet => ({
  datasheet_id: "11111111-1111-1111-1111-111111111111",
  chip_name: "TestChip",
  footprinter_string: "soic2",
  pin_information: [
    { pin_number: "1", name: ["VCC"] },
    { pin_number: "2", name: ["GND"] },
  ],
  pin_attributes: {
    VCC: { requiresPower: true, requiresVoltage: "3.3V" },
    GND: { requiresGround: true },
  },
  ...overrides,
})

/** Execute only source generated by this adapter, never the API's generated_tsx. */
const componentFromGeneratedSource = (tsx: string) => {
  const js = new Bun.Transpiler({
    loader: "tsx",
    tsconfig: { compilerOptions: { jsx: "react" } },
  })
    .transformSync(tsx)
    .replace(/export const /, "const ")
    .replace(/export default ([A-Za-z0-9_]+);?/, "return $1;")
  return new Function("React", js)(React) as React.ComponentType<{
    name: string
  }>
}

const renderLocally = async (record: CachedDatasheet) => {
  const previousFetch = globalThis.fetch
  const externalRequests: RequestInfo[] = []
  globalThis.fetch = (async (input: RequestInfo) => {
    externalRequests.push(input)
    throw new Error("The cached datasheet import attempted a network request")
  }) as typeof fetch
  try {
    const part = adaptCachedDatasheet({ datasheet: record })
    const Component = componentFromGeneratedSource(part.tsx)
    const circuit = new Circuit({
      platform: {
        partsEngineDisabled: true,
        checkAvailability: false,
        enablePartOrientationAnalysis: false,
        useCloudAutorouter: false,
      },
    })
    circuit.add(
      React.createElement(
        "board",
        { width: "20mm", height: "20mm", routingDisabled: true },
        React.createElement(Component, { name: "U1" }),
      ),
    )
    await circuit.renderUntilSettled()
    expect(externalRequests).toHaveLength(0)
    return { part, json: circuit.getCircuitJson() }
  } finally {
    globalThis.fetch = previousFetch
  }
}

test("adapts a cached API envelope to a compact local component without evaluating source", () => {
  const record = fixture()
  const original = JSON.stringify(record)
  const part = adaptCachedDatasheet({
    datasheet: {
      ...record,
      generated_tsx: 'throw new Error("Do not evaluate API source")',
      datasheet_pdf_urls: ["https://example.com/datasheet.pdf"],
      symbol_tsx: "fetch('https://example.com')",
    },
  })
  expect(part.chipName).toBe("TestChip")
  expect(part.datasheetId).toBe(record.datasheet_id)
  expect(part.tsx).toContain('footprint={"soic2"}')
  expect(part.tsx).toContain('manufacturerPartNumber="TestChip"')
  expect(part.tsx).not.toContain("example.com")
  expect(part.tsx).not.toContain("Do not evaluate")
  expect(part.tsx).not.toContain("pcb_smtpad")
  expect(part.pinAttributes).toEqual({
    pin1: { requiresPower: true, requiresVoltage: "3.3V" },
    pin2: { requiresGround: true },
  })
  expect(JSON.stringify(record)).toBe(original)
})

test("permits absent optional metadata and preserves false and zero attributes", () => {
  const noAttributes = adaptCachedDatasheet(fixture({ pin_attributes: null }))
  expect(noAttributes.pinAttributes).toEqual({})
  const part = adaptCachedDatasheet(
    fixture({
      pin_attributes: { pin1: { requiresPower: false, requiresVoltage: 0 } },
    }),
  )
  expect(part.pinAttributes.pin1).toEqual({
    requiresPower: false,
    requiresVoltage: 0,
  })
})

test("renders generated source with local copper and electrical attributes", async () => {
  const { json } = await renderLocally(fixture())
  const pads = json.filter((element) => element.type === "pcb_smtpad")
  expect(pads).toHaveLength(2)
  expect(pads.every((pad) => Boolean(pad.pcb_port_id))).toBe(true)
  expect(
    json.find((element) => element.type === "source_component"),
  ).toMatchObject({
    manufacturer_part_number: "TestChip",
  })
  expect(
    json.find(
      (element) => element.type === "source_port" && element.pin_number === 1,
    ),
  ).toMatchObject({
    requires_power: true,
    requires_voltage: "3.3V",
  })
  expect(
    json.find(
      (element) => element.type === "source_port" && element.pin_number === 2,
    ),
  ).toMatchObject({
    requires_ground: true,
  })
})

test("shared generation escapes part names and keeps absent attributes uninferred", async () => {
  const chipName = 'Test"Chip\n<&'
  const { json } = await renderLocally(
    fixture({ chip_name: chipName, pin_attributes: null }),
  )
  expect(
    json.find((element) => element.type === "source_component"),
  ).toMatchObject({ manufacturer_part_number: chipName })
  const powerPin = json.find(
    (element) => element.type === "source_port" && element.pin_number === 1,
  )
  const groundPin = json.find(
    (element) => element.type === "source_port" && element.pin_number === 2,
  )
  if (powerPin?.type !== "source_port" || groundPin?.type !== "source_port") {
    throw new Error("Generated source ports missing")
  }
  expect(powerPin.requires_power).toBeUndefined()
  expect(groundPin.requires_ground).toBeUndefined()
})

test("keeps an explicitly labeled QFN thermal pin57 attached to its copper", async () => {
  const record = fixture({
    chip_name: "RP2040",
    footprinter_string:
      "qfn56_thermalpad3.1mmx3.1mm_p0.4001mm_w7.8999mm_h7.9001mm_pw0.2mm_pl0.85mm",
    pin_information: [
      ...Array.from({ length: 56 }, (_, index) => ({
        pin_number: String(index + 1),
        name: [`IO${index + 1}`],
      })),
      { pin_number: "57", name: ["GND", "thermalpad"] },
    ],
    pin_attributes: { pin57: { requiresGround: true } },
  })
  const { part, json } = await renderLocally(record)
  expect(part.pinLabels.pin57).toContain("thermalpad")
  const pad = json.find(
    (element) =>
      element.type === "pcb_smtpad" &&
      element.port_hints?.includes("thermalpad"),
  )
  if (pad?.type !== "pcb_smtpad") throw new Error("Thermal copper missing")
  const pcbPort = json.find(
    (element) =>
      element.type === "pcb_port" && element.pcb_port_id === pad.pcb_port_id,
  )
  if (pcbPort?.type !== "pcb_port") throw new Error("Thermal PCB port missing")
  expect(
    json.find(
      (element) =>
        element.type === "source_port" &&
        element.source_port_id === pcbPort.source_port_id,
    ),
  ).toMatchObject({ pin_number: 57, requires_ground: true })
})

test("preserves BGA ball ownership in generated source and local core rendering", async () => {
  const record = fixture({
    footprinter_string: "bga4_grid2x2",
    pin_information: [
      { pin_number: "B2", name: ["GND"] },
      { pin_number: "A2", name: ["D-"] },
      { pin_number: "B1", name: ["D+"] },
      { pin_number: "A1", name: ["VCC"] },
    ],
    pin_attributes: {
      A1: { requiresVoltage: "3.3V" },
      pinB1: { requiresGround: true, isBidirectional: true },
    },
  })
  const { part, json } = await renderLocally(record)
  expect(part.pinLabels.pin1).toContain("A1")
  expect(part.pinLabels.pin3).toContain("B1")
  expect(part.pinAttributes.pin3?.isBidirectional).toBe(true)
  expect(part.pinLabels.pin2).not.toEqual(part.pinLabels.pin3)
  const pad = json.find(
    (element) =>
      element.type === "pcb_smtpad" && element.port_hints?.includes("B1"),
  )
  if (pad?.type !== "pcb_smtpad") throw new Error("B1 copper missing")
  const pcbPort = json.find(
    (element) =>
      element.type === "pcb_port" && element.pcb_port_id === pad.pcb_port_id,
  )
  if (pcbPort?.type !== "pcb_port") throw new Error("B1 PCB port missing")
  expect(
    json.find(
      (element) =>
        element.type === "source_port" &&
        element.source_port_id === pcbPort.source_port_id,
    ),
  ).toMatchObject({ pin_number: 3, requires_ground: true })
})

test("physical attributes override shared signal attributes without changing pin identity", () => {
  const part = adaptCachedDatasheet(
    fixture({
      pin_information: [
        { pin_number: "1", name: ["GND"] },
        { pin_number: "2", name: ["GND"] },
      ],
      pin_attributes: {
        GND: { requiresGround: true },
        pin1: { requiresGround: false },
      },
    }),
  )
  expect(part.pinAttributes).toEqual({
    pin1: { requiresGround: false },
    pin2: { requiresGround: true },
  })
})

test("rejects missing, conflicting, and ambiguous physical mappings", () => {
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        pin_information: [{ pin_number: "1", name: ["VCC"] }],
      }),
    ),
  ).toThrow("maps to 0 physical pins")
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        pin_information: [
          { pin_number: "1", name: ["VCC"] },
          { pin_number: "01", name: ["GND"] },
        ],
      }),
    ),
  ).toThrow("duplicate physical pin")
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        footprinter_string: "bga4_grid2x2",
        pin_information: [
          { pin_number: "1", name: ["NUMERIC"] },
          { pin_number: "A1", name: ["BALL"] },
          { pin_number: "A2", name: ["IO"] },
          { pin_number: "B1", name: ["IO"] },
          { pin_number: "B2", name: ["GND"] },
        ],
      }),
    ),
  ).toThrow("maps to 2 physical pins")
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        footprinter_string: "qfn8_thermalpad1.6x1.6mm",
        pin_information: Array.from({ length: 9 }, (_, index) => ({
          pin_number: String(index + 1),
          name: ["GND"],
        })),
      }),
    ),
  ).toThrow("thermalpad maps to 0 physical pins")
})

test("rejects remote recipes and malformed or unmapped electrical attributes", () => {
  expect(() =>
    adaptCachedDatasheet(
      fixture({ footprinter_string: "https://example.com/part.json" }),
    ),
  ).toThrow("local recipe")
  expect(() =>
    adaptCachedDatasheet({
      ...fixture(),
      pin_attributes: { pin1: { requiresPower: "yes" } },
    }),
  ).toThrow("requiresPower")
  expect(() =>
    adaptCachedDatasheet(
      fixture({ pin_attributes: { pin3: { requiresGround: true } } }),
    ),
  ).toThrow("unknown pin pin3")
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        pin_attributes: {
          "1": { requiresGround: true },
          pin1: { requiresGround: false },
        },
      }),
    ),
  ).toThrow("conflicting physical requiresGround")
  expect(() =>
    adaptCachedDatasheet(
      fixture({
        footprinter_string: "bga4_grid2x2",
        pin_information: [
          { pin_number: "A1", name: ["B1"] },
          { pin_number: "A2", name: ["GND"] },
          { pin_number: "B1", name: ["D+"] },
          { pin_number: "B2", name: ["D-"] },
        ],
      }),
    ),
  ).toThrow("aliases another physical pin B1")
})
